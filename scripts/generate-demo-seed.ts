/*
 * Writes supabase/seed.sql (categories, required) and supabase/seed-demo.sql
 * (the sample families and requests, for a staging project only) from the
 * same data the site uses when Supabase isn't connected.
 *
 *   node scripts/generate-demo-seed.ts
 */
import { writeFileSync } from "node:fs";
import { SAMPLE_FAMILIES, SAMPLE_REQUESTS } from "../src/lib/data/sample-catalog.ts";
import { CATEGORIES } from "../src/lib/taxonomy.ts";

const lit = (value: string | number | boolean | null | undefined): string => {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return `'${value.replace(/'/g, "''")}'`;
};
const json = (value: unknown) => `${lit(JSON.stringify(value))}::jsonb`;
const textArray = (values: string[]) => (values.length ? `array[${values.map(lit).join(", ")}]::text[]` : "'{}'::text[]");
const category = (slug: string) => `(select id from public.categories where slug = ${lit(slug)})`;

const header = (purpose: string) =>
  `-- Generated by scripts/generate-demo-seed.ts. Do not edit by hand.\n-- ${purpose}\n\n`;

const seed =
  header("Catalog categories. Run once after the migrations; safe to re-run.") +
  `insert into public.categories (slug, name, description, sort_order) values\n` +
  CATEGORIES.map((c) => `  (${lit(c.slug)}, ${lit(c.name)}, ${lit(c.description)}, ${c.sort_order})`).join(",\n") +
  `\non conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;\n`;

const families = SAMPLE_FAMILIES.map(
  (f) => `insert into public.families (id, slug, name, summary, description, category_id, status, price_paise, lod, host, is_parametric, tags, parameters, types, drawing, downloads_count, published_at)
values (${lit(f.id)}, ${lit(f.slug)}, ${lit(f.name)}, ${lit(f.summary)}, ${lit(f.description)}, ${category(f.category_slug)}, 'published', ${f.price_paise}, ${lit(f.lod)}, ${lit(f.host)}, ${f.is_parametric}, ${textArray(f.tags)}, ${json(f.parameters)}, ${json(f.types)}, ${lit(f.drawing)}, ${f.downloads_count}, ${lit(f.published_at)})
on conflict (id) do nothing;`,
);

const files = SAMPLE_FAMILIES.flatMap((f) =>
  f.files.map(
    (file) =>
      `insert into public.family_files (id, family_id, kind, revit_version, file_name, storage_path, size_bytes) values (${lit(file.id)}, ${lit(f.id)}, ${lit(file.kind)}, ${lit(file.revit_version)}, ${lit(file.file_name)}, ${lit(`${f.id}/demo-${file.file_name}`)}, ${file.size_bytes}) on conflict (id) do nothing;`,
  ),
);

const changelog = SAMPLE_FAMILIES.flatMap((f) =>
  [...f.changelog].reverse().map(
    (c) =>
      `insert into public.family_changelog (id, family_id, version_label, notes, created_at) values (${lit(c.id)}, ${lit(f.id)}, ${lit(c.version_label)}, ${lit(c.notes)}, ${lit(c.created_at)}) on conflict (id) do nothing;`,
  ),
);

const requests = SAMPLE_REQUESTS.map(
  (r) => `insert into public.requests (id, title, details, category_id, status, family_id, votes_count, created_at)
values (${lit(r.id)}, ${lit(r.title)}, ${lit(r.details)}, ${r.category_slug ? category(r.category_slug) : "null"}, ${lit(r.status)}, ${r.family_slug ? `(select id from public.families where slug = ${lit(r.family_slug)})` : "null"}, ${r.votes_count}, ${lit(r.created_at)})
on conflict (id) do nothing;`,
);

const demo =
  header(
    "Sample families and requests for a staging project. The file rows point at objects that\n-- don't exist, so downloads fail until you upload real files. Never run this in production.",
  ) +
  ["-- Families", ...families, "", "-- Files", ...files, "", "-- Changelog", ...changelog, "", "-- Requests", ...requests].join("\n") +
  "\n";

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), seed);
writeFileSync(new URL("../supabase/seed-demo.sql", import.meta.url), demo);
console.log(`seed.sql: ${CATEGORIES.length} categories. seed-demo.sql: ${SAMPLE_FAMILIES.length} families, ${SAMPLE_REQUESTS.length} requests.`);
