import { CATEGORIES } from "../taxonomy.ts";
import type { Family, FamilyFile, FamilyRequest, Parameter, TypeCatalog } from "../types.ts";

/*
 * Sample catalog. Powers the site before Supabase is connected and generates
 * supabase/seed-demo.sql for a staging project. Replace with real families.
 */

type SampleInput = {
  n: number;
  slug: string;
  name: string;
  summary: string;
  description: string;
  category: string;
  price: number;
  lod: Family["lod"];
  host: Family["host"];
  parametric?: boolean;
  tags: string[];
  drawing: string;
  versions: number[];
  downloads: number;
  published: string;
  version?: string;
  parameters: Parameter[];
  types?: TypeCatalog;
  changelog?: { version: string; notes: string; date: string }[];
};

const id = (n: number, prefix = "0000") => `${prefix}0000-0000-4000-8000-${String(n).padStart(12, "0")}`;

const p = (group: string, name: string, value: string, unit?: string, kind: Parameter["kind"] = "type"): Parameter => ({
  group,
  name,
  value,
  unit,
  kind,
});

function build(input: SampleInput): Family {
  const category = CATEGORIES.find((c) => c.slug === input.category);
  if (!category) throw new Error(`Unknown category ${input.category}`);

  const fileBase = input.name.replace(/[^A-Za-z0-9]+/g, "_").replace(/_$/, "");
  const files: FamilyFile[] = input.versions.map((v, i) => ({
    id: id(input.n * 100 + i, "f000"),
    kind: "rfa",
    revit_version: v,
    file_name: `RVN_${fileBase}_R${v}.rfa`,
    size_bytes: 380_000 + ((input.n * 7919 + v) % 900_000),
  }));
  if (input.types?.rows.length) {
    files.push({
      id: id(input.n * 100 + 99, "f000"),
      kind: "txt",
      revit_version: null,
      file_name: `RVN_${fileBase}.txt`,
      size_bytes: 1_200 + input.types.rows.length * 64,
    });
  }

  const sorted = [...input.versions].sort((a, b) => a - b);

  return {
    id: id(input.n),
    slug: input.slug,
    name: input.name,
    summary: input.summary,
    description: input.description,
    category_id: category.id,
    category_slug: category.slug,
    category_name: category.name,
    status: "published",
    price_paise: input.price * 100,
    lod: input.lod,
    host: input.host,
    is_parametric: input.parametric ?? true,
    tags: input.tags,
    cover_path: null,
    gallery_paths: [],
    drawing: input.drawing,
    version_label: input.version ?? "1.0",
    revit_versions: sorted,
    revit_min_version: sorted[0] ?? null,
    downloads_count: input.downloads,
    saves_count: Math.round(input.downloads / 9),
    published_at: input.published,
    updated_at: input.changelog?.[0]?.date ?? input.published,
    parameters: input.parameters,
    types: input.types ?? { columns: [], rows: [] },
    files,
    changelog: (input.changelog ?? []).map((c, i) => ({
      id: id(input.n * 10 + i, "c000"),
      version_label: c.version,
      notes: c.notes,
      created_at: c.date,
    })),
  };
}

